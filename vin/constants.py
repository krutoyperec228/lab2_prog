import re


# Структура VIN:
#   позиции 1-8   : [A-HJ-NPR-Z0-9]
#   позиция 9     : [0-9X]
#   позиции 10-17 : [A-HJ-NPR-Z0-9]

VIN_PATTERN = re.compile(
    r'[A-HJ-NPR-Z0-9]{8}[0-9X][A-HJ-NPR-Z0-9]{8}'
)
VIN_SEARCH_PATTERN = re.compile(
    r'(?<![A-Z0-9])[A-HJ-NPR-Z0-9]{8}[0-9X][A-HJ-NPR-Z0-9]{8}(?![A-Z0-9])'
)

